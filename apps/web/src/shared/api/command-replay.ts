import { isWorkspaceCommandResponse } from "./workspace-shape";

type StoragePort = Pick<Storage, "getItem" | "setItem" | "removeItem">;
type ReplayPorts = {
  storage: () => StoragePort;
  fetch: (url: string, options: RequestInit) => Promise<Response>;
  fingerprint: (value: string) => Promise<string>;
};
export const commandReplayStoragePrefix = "artmate-wms:unresolved-command:v1:";
const prefix = commandReplayStoragePrefix;
const inFlight = new Set<string>();
const storageError =
  "Браузер не может сохранить защиту от повторной записи. Разрешите хранилище вкладки и повторите действие.";

function stableJson(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(stableJson).join(",")}]`;
  if (value !== null && typeof value === "object")
    return `{${Object.keys(value)
      .sort()
      .map(
        (key) =>
          `${JSON.stringify(key)}:${stableJson((value as Record<string, unknown>)[key])}`,
      )
      .join(",")}}`;
  return JSON.stringify(value);
}
function message(data: unknown): string | null {
  if (!data || typeof data !== "object" || !("message" in data)) return null;
  const raw = (data as { message: unknown }).message;
  return typeof raw === "string"
    ? raw
    : Array.isArray(raw)
      ? raw.filter((item) => typeof item === "string").join(". ")
      : null;
}

/** No automatic retries: an explicit retry reuses only its unresolved key. */
export async function fetchReplaySafeCommand<T>(
  url: string,
  options: RequestInit,
  ports: ReplayPorts,
): Promise<T> {
  let body: Record<string, unknown>;
  try {
    if (typeof options.body !== "string") throw new Error();
    const parsed: unknown = JSON.parse(options.body);
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed))
      throw new Error();
    body = parsed as Record<string, unknown>;
  } catch {
    throw new Error(
      "Не удалось подготовить команду. Обновите страницу и повторите действие.",
    );
  }
  const proposedId = body.requestId;
  if (
    typeof proposedId !== "string" ||
    !proposedId.trim() ||
    proposedId.length > 150
  )
    throw new Error("Не удалось определить ключ команды. Обновите страницу.");
  const { requestId: _requestId, ...payload } = body;
  let fingerprint: string;
  try {
    fingerprint = await ports.fingerprint(
      stableJson({
        method: (options.method ?? "POST").toUpperCase(),
        url,
        body: payload,
      }),
    );
  } catch {
    throw new Error(
      "Браузер не может подготовить защиту от повторной записи. Обновите страницу.",
    );
  }
  if (inFlight.has(fingerprint))
    throw new Error(
      "Такое действие уже отправляется. Дождитесь подтверждения перед повтором.",
    );
  inFlight.add(fingerprint);
  try {
    let storage: StoragePort;
    let canonicalId: string;
    const key = `${prefix}${fingerprint}`;
    try {
      storage = ports.storage();
      const existing = storage.getItem(key);
      if (existing !== null && (!existing.trim() || existing.length > 150))
        throw new Error();
      canonicalId = existing ?? proposedId;
      // Persist before sending, even on a retry, to verify storage is writable.
      storage.setItem(key, canonicalId);
    } catch {
      throw new Error(storageError);
    }
    let response: Response;
    try {
      response = await ports.fetch(url, {
        ...options,
        body: stableJson({ ...payload, requestId: canonicalId }),
      });
    } catch {
      throw new Error(
        "Не удалось получить подтверждение от сервера. Повторите действие — повторная отправка защищена от дублирования.",
      );
    }
    let data: unknown;
    try {
      data = await response.json();
    } catch {
      data = undefined;
    }
    if (!response.ok) {
      // 408 can be generated by an intermediary after an ambiguous timeout.
      if (
        response.status >= 400 &&
        response.status < 500 &&
        response.status !== 408
      ) {
        try {
          storage.removeItem(key);
        } catch {
          throw new Error(storageError);
        }
      }
      throw new Error(
        message(data) ?? "Сервер не подтвердил действие. Повторите попытку.",
      );
    }
    if (!isWorkspaceCommandResponse(data))
      throw new Error(
        "Сервер вернул неподтверждённый результат. Повторите действие — прежняя запись не продублируется.",
      );
    try {
      storage.removeItem(key);
    } catch {
      throw new Error(
        "Сервер выполнил действие, но браузер не сохранил подтверждение. Повторите его для безопасного получения результата.",
      );
    }
    return data as T;
  } finally {
    inFlight.delete(fingerprint);
  }
}

export async function commandFingerprint(value: string): Promise<string> {
  const hash = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(value),
  );
  return Array.from(new Uint8Array(hash), (byte) =>
    byte.toString(16).padStart(2, "0"),
  ).join("");
}
